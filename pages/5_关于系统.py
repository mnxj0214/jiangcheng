import streamlit as st

st.title("ℹ️ 关于江城智旅")
st.markdown("""
### 项目背景
本系统由“江城智旅”项目组开发，面向芜湖市镜湖区文旅局的实际业务需求。

### 核心功能
- **AI策划与文案**：基于大模型，结合本地文化生成策划案和风险提醒。
- **排期冲突检测**：自动检测活动时间冲突，并用甘特图可视化排期。
- **资源统筹与路线**：智能推荐联动商圈，提升消费带动能力。
- **数据复盘**：基于活动数据自动生成复盘报告。

### 技术栈
- Python + Streamlit
- 智谱清言 GLM-4-Flash 大模型
- Plotly 数据可视化
- Pandas 数据处理

### 落地价值
本系统可无缝接入文旅局真实数据，实现“策划-排期-执行-复盘”全流程智能化，显著提升活动组织效率与区域消费带动能力。
""")